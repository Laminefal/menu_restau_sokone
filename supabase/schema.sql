alter table public.expenses enable row level security;

create table if not exists public.debts (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  creditor text not null,
  amount numeric(10, 2) not null check (amount > 0),
  description text,
  debt_date date not null default current_date,
  paid_at timestamptz,
  debt_type text not null default 'Je dois'
    check (debt_type in ('Je dois', 'On me doit')),
  status text not null default 'À payer' check (status in ('À payer', 'Payée')),
  created_at timestamptz not null default now()
);

alter table public.debts add column if not exists paid_at timestamptz;
alter table public.debts add column if not exists debt_type text not null default 'Je dois';
alter table public.debts drop constraint if exists debts_debt_type_check;
alter table public.debts add constraint debts_debt_type_check
  check (debt_type in ('Je dois', 'On me doit'));

create or replace function public.prevent_paid_debt_reopening()
returns trigger
language plpgsql
as $$
begin
  if old.status = 'Payée' and new.status <> 'Payée' then
    raise exception 'Une dette payée ne peut pas être réouverte';
  end if;
  return new;
end;
$$;

drop trigger if exists debts_prevent_reopening on public.debts;
create trigger debts_prevent_reopening
  before update on public.debts
  for each row execute function public.prevent_paid_debt_reopening();

alter table public.debts enable row level security;

