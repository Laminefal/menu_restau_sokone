  created_at timestamptz not null default now()
);

alter table public.menu_items drop constraint if exists menu_items_name_not_empty;
alter table public.menu_items add constraint menu_items_name_not_empty
  check (length(trim(name)) > 0);

create table if not exists public.restaurant_menu_days (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  menu_item_id bigint not null references public.menu_items(id) on delete cascade,
  menu_date date not null default current_date,
  created_at timestamptz not null default now(),
  unique (restaurant_id, menu_item_id, menu_date)
);

create table if not exists public.restaurant_hours (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  opens_at time,
  closes_at time,
  is_closed boolean not null default false,
  unique (restaurant_id, day_of_week)
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  label text,
  category text not null default 'Autre',
  amount numeric(10, 2) not null check (amount > 0),
  expense_date date not null default current_date,
  description text,
  created_at timestamptz not null default now()
);

alter table public.expenses add column if not exists description text;
